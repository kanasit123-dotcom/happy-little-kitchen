self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => (
        key.startsWith('happy-little-kitchen-') || key.startsWith('lilly-playhouse-')
      ) && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  if (event.request.mode === 'navigate') {
    // ขอ index.html จากเซิร์ฟเวอร์เสมอ (ข้าม HTTP cache 10 นาทีของ GitHub Pages) จะได้เห็นเวอร์ชันใหม่ทันทีที่ deploy
    event.respondWith(
      fetch(new Request(event.request, { cache: 'no-cache' })).then((response) => {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put('index.html', copy)).catch(() => {});
        return response;
      }).catch(() => caches.match('index.html'))
    );
    return;
  }
  event.respondWith(
    caches.match(event.request).then((cached) => cached || fetch(event.request).then((response) => {
      const copy = response.clone();
      caches.open(CACHE).then((cache) => cache.put(event.request, copy)).catch(() => {});
      return response;
    }).catch(() => caches.match('index.html')))
  );
});
